-- 4. HARDENED SIGNUP TRIGGER: handle_new_user()
-- IGNORES all client-submitted role, is_vip, vip_expires_at, credits in metadata.
-- ONLY accepts a sanitized username ([a-zA-Z0-9_.-], 3-30 chars).
-- New users are strictly role='USER', is_vip=false, credits=10 (or configured starter bonus).
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_raw_username TEXT;
    v_clean_username VARCHAR(50);
    v_default_credits INTEGER := 10;
BEGIN
    -- Extract and sanitize username
    v_raw_username := NEW.raw_user_meta_data->>'username';
    IF v_raw_username IS NOT NULL AND v_raw_username ~ '^[a-zA-Z0-9_.-]{3,30}$' THEN
        v_clean_username := v_raw_username;
    ELSE
        -- Fallback to sanitized email handle + 4 random hex digits
        v_clean_username := regexp_replace(split_part(NEW.email, '@', 1), '[^a-zA-Z0-9_.-]', '', 'g');
        IF length(v_clean_username) < 3 THEN
            v_clean_username := 'trader';
        END IF;
        v_clean_username := substring(v_clean_username, 1, 24) || '_' || substring(md5(random()::text), 1, 4);
    END IF;

    -- Guarantee unique username conflict avoidance
    IF EXISTS (SELECT 1 FROM public.users WHERE username = v_clean_username) THEN
        v_clean_username := substring(v_clean_username, 1, 22) || '_' || substring(md5(random()::text), 1, 6);
    END IF;

    -- Strict non-negotiable default values: USER role, no VIP, default welcome credits
    INSERT INTO public.users (
        auth_user_id,
        username,
        email,
        role,
        credits,
        is_vip,
        vip_expires_at,
        registration_ip
    )
    VALUES (
        NEW.id,
        v_clean_username,
        LOWER(TRIM(NEW.email)),
        'USER',
        v_default_credits,
        FALSE,
        NULL,
        'supabase_auth'
    )
    ON CONFLICT (email) DO UPDATE SET
        auth_user_id = EXCLUDED.auth_user_id,
        updated_at = NOW();

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

