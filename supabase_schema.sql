-- 3. RECURSION-SAFE SECURITY DEFINER ADMIN HELPER
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.users
        WHERE auth_user_id = auth.uid() AND role = 'ADMIN'
    );
$$;

